"""Downloadable audit reports (Markdown) built from stored records."""
from database import repositories as repo


def audit_markdown(sid):
    sub = repo.get_submission(sid)
    revs = repo.revisions(sid)
    lines = [f"# BrandCanon audit report — {sub['title']}", "",
             f"- Channel: {sub['channel']} · Content type: {sub['content_type']} · Product: {sub['product'] or '—'}",
             f"- Status: {sub['status']} · Author: {sub['author_name']}", ""]
    for rev in revs:
        rep = repo.latest_report(rev["id"])
        lines += [f"## Revision {rev['revision_no']} ({rev['created_at'][:16].replace('T', ' ')})", "", "> " + rev["text"].replace("\n", "\n> "), ""]
        if not rep:
            continue
        lines += [f"**Result:** {rep['overall_status']} · high {rep['n_high']} · medium {rep['n_medium']} · low {rep['n_low']} · engine: {rep['engine']}", ""]
        for i, f in enumerate(repo.findings(rep["id"]), 1):
            lines += [f"{i}. **{f['severity'].upper()} · {f['category']} · {f['classification']}** — “{f['quote']}”",
                      f"   - {f['message']}",
                      f"   - Evidence: {f['evidence_source'] or 'none found'}" + (f" — “{f['evidence_text']}”" if f["evidence_text"] else ""),
                      f"   - Suggested: {f['suggestion'] or '—'} · Root cause: {f['root_cause']} · Confidence: {f['confidence']}",
                      f"   - Disposition: {f['disposition']}" + (f" ({f['disposition_reason']})" if f["disposition_reason"] else "")]
        lines.append("")
    appr = repo.approvals(sid)
    if appr:
        lines += ["## Review decisions", ""] + [f"- {a['created_at'][:10]} · {a['reviewer_name']} · v{a['revision_no']}: **{a['outcome']}** — {a['rationale']}" for a in appr]
    lines += ["", "_Generated by BrandCanon. Findings are recommendations; final approval is a human decision._"]
    return "\n".join(lines)
